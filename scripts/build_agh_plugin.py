"""Generate roof data and bundle the plugin; --check verifies committed artifacts."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
from urllib.parse import urlsplit
from guangzhu.templates import catalog_data

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / "agh-plugin/guangzhu-studio"
CLIENT = Path("extensions/main/client")
TOOL_PREFIX = "mcp_guangzhu_df14eb73_"
# 开发版 8765、安装版 8766；插件只接受这两个本机桌面源，并回复给先打招呼的那一个。
DESKTOP_ORIGINS = ("http://127.0.0.1:8765", "http://127.0.0.1:8766")
HEADER = "// @generated by scripts/build_agh_plugin.py; do not edit.\n"


def make_data(tool_prefix=TOOL_PREFIX, desktop_origins=DESKTOP_ORIGINS):
    if not re.fullmatch(r"[A-Za-z0-9_]+_", tool_prefix): raise ValueError("工具前缀不正确")
    for desktop_origin in desktop_origins:
        origin = urlsplit(desktop_origin)
        if (origin.scheme != "http" or origin.hostname != "127.0.0.1" or not origin.port
                or origin.netloc != f"127.0.0.1:{origin.port}" or origin.path or origin.query or origin.fragment):
            raise ValueError("桌面源必须是 http://127.0.0.1:<端口>，不带路径")
    templates = []
    for identifier, (_, project) in catalog_data(all=True, root=ROOT, mine=False).items():
        roof = project["roof"]
        templates.append(dict(id=identifier, name=project["name"], outline=roof["outline"],
                              obstacles=roof.get("obstacles", []), keepouts=roof.get("keepouts", [])))
    return dict(templates=templates, toolPrefix=tool_prefix, desktopOrigins=list(desktop_origins))


def build(package, tool_prefix=TOOL_PREFIX, desktop_origins=DESKTOP_ORIGINS):
    package = Path(package).resolve()
    target = package / CLIENT / "data.js"
    target.parent.mkdir(parents=True, exist_ok=True)
    data = json.dumps(make_data(tool_prefix, desktop_origins), ensure_ascii=False, indent=2, allow_nan=False)
    target.write_text(HEADER + "export const DATA = " + data + ";\n", encoding="utf-8", newline="\n")
    node, esbuild = shutil.which("node"), PLUGIN / "node_modules/esbuild/bin/esbuild"
    if not node or not esbuild.is_file(): raise RuntimeError("先在插件目录运行 npm ci 安装锁定的 esbuild")
    subprocess.run([node, str(esbuild), "src/index.jsx", "--bundle", "--format=esm", "--target=es2022",
        "--external:react", "--external:react/jsx-runtime", "--external:antd", "--charset=utf8",
        "--banner:js=" + HEADER.rstrip(), "--outfile=" + str(CLIENT / "index.js")],
        cwd=package, check=True, timeout=90)


def release(directory):
    metadata = json.loads((PLUGIN / 'package.json').read_text(encoding='utf-8'))
    for key in ('devDependencies', 'scripts'): metadata.pop(key, None)
    files = {'package.json': (json.dumps(metadata, ensure_ascii=False, indent=2) + '\n').encode('utf-8'),
             'index.mjs': (PLUGIN / 'index.mjs').read_bytes()}
    for name in ('extensions', 'licenses'):
        files.update((path.relative_to(PLUGIN).as_posix(), path.read_bytes())
                     for path in sorted((PLUGIN / name).rglob('*')) if path.is_file())
    digest = hashlib.sha256(b''.join(name.encode() + b'\0' + files[name] for name in sorted(files))).hexdigest()[:12]
    target = Path(directory) / f"{metadata['name']}-{metadata['version']}-{digest}"
    for name, data in files.items():
        path = target / name
        if path.exists() and path.read_bytes() != data: raise RuntimeError('发布快照已被修改：' + name)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return target


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tool-prefix", default=TOOL_PREFIX)
    parser.add_argument("--desktop-origin", action="append", dest="desktop_origins")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--release", action="store_true", help="同时生成 dist/agh-plugin 下的纯运行发布包")
    args = parser.parse_args(argv)
    try:
        if args.check:
            with tempfile.TemporaryDirectory(prefix="guangzhu-plugin-check-") as directory:
                package = Path(directory) / "agh-plugin/guangzhu-studio"
                shutil.copytree(PLUGIN / "src", package / "src")
                shared = Path(directory) / "desktop/web/tool-results.js"
                shared.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(ROOT / "desktop/web/tool-results.js", shared)
                shutil.copyfile(ROOT / "desktop/web/model-choices.js", shared.with_name("model-choices.js"))
                skin = Path("extensions/main/skins/agnes.client.json")
                (package / skin).parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(PLUGIN / skin, package / skin)
                build(package, args.tool_prefix, args.desktop_origins or DESKTOP_ORIGINS)
                for name in ("data.js", "index.js"):
                    if (package / CLIENT / name).read_bytes() != (PLUGIN / CLIENT / name).read_bytes():
                        raise RuntimeError("入库产物与重建不一致：" + name)
        else: build(PLUGIN, args.tool_prefix, args.desktop_origins or DESKTOP_ORIGINS)
        if args.release: print('Package source: file:./' + release(ROOT / 'dist/agh-plugin').relative_to(ROOT).as_posix())
        print("Plugin artifacts match" if args.check else "Plugin artifacts generated")
        return 0
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == "__main__": raise SystemExit(main())
