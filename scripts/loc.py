"""Count nonblank lines in maintained source files, grouped by top directory."""

from __future__ import annotations

import argparse
from collections import defaultdict
import os
from pathlib import Path


SOURCE_SUFFIXES = {
    ".py", ".ps1", ".cmd", ".bat", ".js", ".jsx", ".mjs", ".cjs",
    ".ts", ".tsx", ".css", ".scss", ".sass", ".html", ".htm",
    ".sh", ".bash", ".sql",
}
EXCLUDED_DIRECTORIES = {
    "docs", "data", "reports", "reviews",
    ".git", ".venv", "venv", "node_modules", "__pycache__", ".pytest_cache",
    ".mypy_cache", ".ruff_cache", ".tox", ".cache", "cache", "dist", "build",
    "coverage", "htmlcov", "tests", "test", "__tests__", "generated",
    "_generated", ".generated",
}
GENERATED_MARKERS = (
    "@generated", "auto-generated", "autogenerated", "automatically generated",
    "generated file", "do not edit",
)


def is_source_file(path: Path) -> bool:
    """Select source files while omitting common tests and generated artifacts."""
    name = path.name.lower()
    stem = path.stem.lower()
    return (
        path.suffix.lower() in SOURCE_SUFFIXES
        and not name.startswith("test_")
        and not stem.endswith(("_test", ".test", ".spec"))
        and ".generated." not in name
        and ".g." not in name
        and not name.endswith((".min.js", ".min.css"))
    )


def count_lines(root: Path) -> dict[str, int]:
    """Count nonblank source lines, including comments, by top-level directory.

    Generated files must use a conventional excluded name/directory or a header
    marker in their first ten lines. Documentation, data, reports and reviews
    directories are excluded entirely. Symlinks are not followed.
    """
    root = root.resolve()
    if not root.is_dir():
        raise ValueError(f"Repository directory does not exist: {root}")
    totals: defaultdict[str, int] = defaultdict(int)
    for directory, subdirectories, filenames in os.walk(root, followlinks=False):
        subdirectories[:] = sorted(
            name for name in subdirectories
            if name.lower() not in EXCLUDED_DIRECTORIES
            and not (Path(directory) / name).is_symlink()
        )
        for name in sorted(filenames):
            path = Path(directory) / name
            if path.is_symlink() or not is_source_file(path):
                continue
            lines = path.read_text(encoding="utf-8-sig").splitlines()
            header = "\n".join(lines[:10]).lower()
            if any(marker in header for marker in GENERATED_MARKERS):
                continue
            relative = path.relative_to(root)
            group = relative.parts[0] if len(relative.parts) > 1 else "."
            totals[group] += sum(bool(line.strip()) for line in lines)
    return dict(sorted(totals.items()))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    arguments = parser.parse_args(argv)
    try:
        totals = count_lines(arguments.root)
    except (OSError, UnicodeError, ValueError) as error:
        print(f"Code line count failed: {error}")
        return 2
    print("Nonblank source lines (comments included; tests/generated files excluded):")
    for directory, count in totals.items():
        print(f"  {directory}: {count}")
    print(f"Total: {sum(totals.values())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
