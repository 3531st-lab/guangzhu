def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def project_for(case, relaxation=False):
    record = Project.model_validate(read(ROOT / "data/roofs" / case["template"] / "project.json"))
    values = copy.deepcopy(case["structured"])
    if relaxation:
        section, field = case["relaxation"]["field"].split(".")
        if section == "roof":
            setattr(record.roof, field, case["relaxation"]["to"])
        else:
            values[field] = case["relaxation"]["to"]
    record.requirements = Requirements(text=case["text"], structured=StructuredRequirements.model_validate(values))
    record.economics = record.economics.model_copy(update=case["economics"])
    return record


def retain(design, identifiers):
    by_id = {module.id: module for module in design.modules}
    assert len(identifiers) == len(set(identifiers)) and set(identifiers) <= by_id.keys()
    design.modules = [by_id[identifier] for identifier in identifiers]
    design.statistics.update(module_count=len(design.modules), dc_kw=len(design.modules) * .55,
                             rows=len({module.row for module in design.modules}))
    return design


def assert_cable_witness(case, record, design, summary, checked):
    expected = {row["id"]: row for row in read(CURRENT_WITNESSES)["witnesses"][case["id"]]["rules"]}
    electric = read(storage._path(record.id, "analysis/v1/electrical.json"))
    cables = electric["cables"]
    positions = {row["label"]: row["point"] for row in cables["positions"]}
    modules = {module.id: module.center[:2] for module in design.modules}
    catalog = electrical.equipment_catalog()
    module = catalog["modules"][record.equipment.module_id]
    for string, row in zip(electric["strings"], cables["dc"]):
        point = positions["I" + str(string["inverter"])]
        assert row["id"] == string["id"] and row["length_m"] == pytest.approx(row["route_m"] * 1.1)
        if row["routing_status"] == "ok":
            # A routed string leaves its inverter, visits every panel and returns, so it is at least twice the farthest panel.
            assert row["route"][0] == pytest.approx(point) and row["route"][-1] == pytest.approx(point)
            assert row["route_m"] >= 2 * max(math.dist(point, modules[mid]) for mid in string["module_ids"]) - 1e-6
        voltage = module["vmp_v"] * len(string["module_ids"])
        drop = .0175 * (1 + .00395 * 100) * row["length_m"] * module["imp_a"] / (row["section_mm2"] * voltage) * 100
        assert row["drop_pct"] == pytest.approx(drop)
        assert row["required_a"] == pytest.approx(1.25 * module["isc_a"])
    for unit, row in zip(electric["per_inverter"], cables["ac"]):
        length = row["route_m"] + 5  # route on the roof and down to the grid point, plus 5 m for terminations
        assert row["route_m"] >= math.dist(positions[row["id"]], positions["GRID"]) + record.roof.height_m - 1e-6
        power_w = catalog["inverters"][unit["inverter_id"]]["rated_ac_kw"] * 1000
        current = power_w / (math.sqrt(3) * 400)
        drop = math.sqrt(3) * .0175 * (1 + .00395 * 70) * length * current / (row["section_mm2"] * 400) * 100
        assert row["length_m"] == pytest.approx(length)
        assert row["drop_pct"] == pytest.approx(drop)
        assert row["required_a"] == pytest.approx(current)
    by_id = {row["id"]: row for row in checked["items"]}
    for code, kind in [("E10", "dc"), ("E11", "ac")]:
        rows = cables[kind]
        maximum = max(row["drop_pct"] for row in rows)
        feasible = all(row["drop_pct"] <= 2 and row["ampacity_a"] >= row["required_a"] and row["routing_status"] == "ok"
                       for row in rows)
        assert by_id[code]["status"] == expected[code]["status"] == ("pass" if feasible else "fail")
        assert by_id[code]["value"] == pytest.approx(expected[code]["value"], abs=1e-6)
        assert by_id[code]["value"] == pytest.approx(maximum)
        assert by_id[code]["limit"] == 2 and by_id[code]["level"] == "hard"
    failed = {code for code in ["E10", "E11"] if expected[code]["status"] == "fail"}
    load = read(storage._path(record.id, 'analysis/v1/structure.json'))
    if load['added_kn_m2'] > record.roof.load_capacity_kn_m2:
        failed.add('L01')
    assert by_id['W01']['status'] == 'na' and record.roof.type == 'flat'
    for code, value, limit in [('U03', summary['economics']['capex_cny'], record.requirements.structured.budget_cny_max),
                               ('U04', summary['economics']['payback_years'], record.requirements.structured.payback_years_max)]:
        if limit is not None and (value is None or value > limit):
            failed.add(code)
    assert {row["id"] for row in checked["items"] if row["level"] == "hard" and row["status"] == "fail"} == failed
    assert summary["rules"]["hard_failed"] == len(failed)
    assert failed == set(read(CURRENT_WITNESSES)['witnesses'][case['id']]['failed'])


def run_witness(case, witness, relaxation=False):
    record = project_for(case, relaxation)
    design = layout.generate_layout(record, witness["params"])
    design = retain(design, witness["kept_module_ids"])
    design.modules_per_string = witness["modules_per_string"]
    storage.save(record)
    storage.save_design(record.id, design)
    summary = analysis.analyze(record.id, 1, offline=True)
    checked = read(storage._path(record.id, "analysis/v1/rules.json"))
    assert len(checked['items']) == 25  # Existing economics rules plus the new hard W01.
    # T30's preserved answer is history; current wind and economic failures are asserted in full below.
    expected, actual = dict(witness["result"]), result_of(summary)
    assert expected.pop("hard_failed") == 0
    for key in ('modules', 'dc_kw', 'p50_kwh'):
        assert actual[key] == pytest.approx(expected[key], abs=.001)
    assert not read(WIND_WITNESSES)['witnesses'][case['id']]['actual_design_pass']  # T31 history: ballast overloaded every roof.
    current = read(CURRENT_WITNESSES)['witnesses'][case['id']]
    assert current['historical_result'] == witness['result']
    assert actual == pytest.approx(result_of(current['summary']), abs=.001)
    assert current['actual_design_pass'] == (summary['rules']['hard_failed'] == 0)
    cash = read(storage._path(record.id, 'analysis/v1/economics.json'))
    assert summary['economics']['capex_cny'] == pytest.approx(sum(r['subtotal_cny'] for r in cash['costs']['items']), abs=.001)
    assert_cable_witness(case, record, design, summary, checked)
    return record, design, summary


def result_of(summary):
    return dict(modules=summary["modules"], dc_kw=summary["dc_kw"], p50_kwh=summary["yield_kwh"]["p50"],
                payback_years=summary["economics"]["payback_years"], capex_cny=summary["economics"]["capex_cny"],
                hard_failed=summary["rules"]["hard_failed"])


