def test_boundary_types_are_material(isolated):
    cases = [case for case in read(CASES) if case["collection"] == "boundary"]
    projects = [project_for(case) for case in cases]
    assert len(projects[0].roof.obstacles) >= 10
    assert len(projects[1].roof.outline) >= 10
    polygon = Polygon(projects[1].roof.outline)
    assert polygon.area < polygon.convex_hull.area
    assert Polygon(projects[2].roof.outline).area <= 500
    record, design, summary = run_witness(cases[3], cases[3]["witness"])
    anchored = structure.calculate(record, design)
    historical = 64.6 * .00981 / (2.384 * 1.096 * math.cos(math.radians(20)))
    assert historical <= record.roof.load_capacity_kn_m2 <= 1.1 * historical
    # The tight roof cannot carry the wind ballast: anchors take the wind, and only an owner who forbids drilling still fails L01.
    assert anchored["added_kn_m2"] <= record.roof.load_capacity_kn_m2 and anchored["wind"]["anchor_count"] > 0
    record.requirements.structured.ballast_only = True
    assert structure.calculate(record, design)["added_kn_m2"] > record.roof.load_capacity_kn_m2
    tight = cases[4]
    reference = tight["payback_reference"]
    best = grid_payback(tight, reference)
    assert best == pytest.approx(reference["best_unshaded_years"], rel=1e-6)
    assert tight["witness"]["result"]["payback_years"] <= tight["structured"]["payback_years_max"] <= 1.03 * best
    assert not {"capacity_kw_min", "capacity_kw_max", "budget_cny_max"} & tight["structured"].keys()
    assert {"walkway_m_min", "keep_clear_ids", "edge_setback_m_min", "budget_cny_max"} <= cases[5]["structured"].keys()


def proof_value(case):
    record = project_for(case)
    kind = case["proof_data"]["kind"]
    catalog = electrical.equipment_catalog()
    module = catalog["modules"][record.equipment.module_id]
    if kind == "load":
        rack = catalog["racking"][record.equipment.racking]
        largest_projection = max(module["width_m"] * (2 * module["length_m"] + rack["module_gap_m"]),
                                 module["length_m"] * (2 * module["width_m"] + rack["module_gap_m"]))
        # Independent uplift-only bound across row/EW, 0–35 degrees and at most two tiers.
        # Subtract 2mm per dimension for the generated corners' 1mm coordinate rounding.
        minimum_area = (module['length_m'] - .002) * (module['width_m'] - .002)
        minimum_pressure = .4 * .5 ** .3 * .65 * 1.2
        return 1.5 * minimum_pressure * minimum_area * math.cos(math.radians(35)) / largest_projection
    if kind == "budget":
        from guangzhu.costs import catalog
        prices = catalog()
        price = prices['module']['value'] + prices['installation']['value']
        return case["structured"]["capacity_kw_min"] * 1000 * price
    if kind in ("area", "usable_area"):
        area = Polygon(record.roof.outline).area
        if kind == "usable_area":
            params = dict(edge_setback_m=case["structured"]["edge_setback_m_min"], obstacle_clearance_m=0, keepout_clearance_m=0)
            area = layout.usable_geometry(record, params)["usable"].area
        projected = module["length_m"] * module["width_m"] * math.cos(math.radians(35))
        return math.floor(area / projected) * module["pmax_w"] / 1000
    if kind == "electrical":
        minimums = []
        for equipment, inverter in itertools.product(catalog["modules"].values(), catalog["inverters"].values()):
            temperatures = electrical._temperatures(record.site, equipment, True)
            hot = equipment["vmp_v"] * (1 + (temperatures["cell_hot_c"] - 25) * equipment["gamma_pmax_pct_c"] / 100)
            minimums.append(math.ceil(inverter["mppt_min_v"] / hot) * equipment["pmax_w"] / 1000)
        return min(minimums)
    if kind == "payback":
        parameters = economics.resolve_parameters(record)[0]
        equipment, inverter, metadata = load_cec_equipment(offline=True)
        energy_ceiling = 8760 * float(inverter["Paco"]) / 1000 / metadata["dc_capacity_kw"]
        price = parameters["self_use_ratio"] * parameters["price_self_cny_kwh"] * 1.7
        price += (1 - parameters["self_use_ratio"]) * parameters["price_export_cny_kwh"]
        net_ceiling = energy_ceiling * price - 1000 * parameters["om_cny_per_w_year"]
        return 1000 * parameters["capex_cny_per_w"] / net_ceiling
    raise AssertionError(kind)


def grid_payback(case, grid=None):
    record = project_for(case)
    if record.economics.capex_cny_per_w is None:
        record.economics.capex_cny_per_w = 2.59  # Original normalized reference; not a complete project quote.
    data, metadata = weather.load_nasa_hourly(record.site.lat, record.site.lon, 2023, offline=True)
    grid = case["proof_data"]["grid"] if grid is None else grid
    paybacks = []
    loss = economics.load_assumptions()["design_system_loss_pct"]["value"]
    for tilt, azimuth in itertools.product(grid["tilt_deg"], grid["azimuth_deg"]):
        generated = yieldsim.simulate_pvlib_detailed(data, record.site.lat, record.site.lon,
                                                   tilt=tilt, azimuth=azimuth, loss_percent=loss, offline=True)
        energy = generated["specific_yield_kwh_kwp"]
        cash = economics.calculate(record, 1, dict(p50=energy, low=energy, high=energy, hourly=generated['hourly']), sensitivity=False)
        paybacks.append(cash["payback_years"] or math.inf)
    return min(paybacks)


