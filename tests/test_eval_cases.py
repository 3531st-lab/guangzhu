def test_plain_text_numbers_match_structured_requirements():
    import re
    for case in read(CASES):
        stated = set()
        for match in re.finditer(r"(\d+(?:\.\d+)?)(万元|元|年|kW|米|度|%)", case["text"]):
            value = float(match[1]) * (10000 if match[2] == "万元" else 1)
            stated.add(value)
        expected = set()
        for field, value in case["structured"].items():
            if field == "tilt_deg_range":
                expected.update(value)
            elif isinstance(value, bool):
                assert not value or '压载' in case["text"], (case["id"], field)  # “按压载支架安装” means no drilling.
            elif isinstance(value, (int, float)):
                expected.add(value)
        for field, value in case["economics"].items():
            expected.add(value * 100 if field == "self_use_ratio" else value)
        # A range written “15到25度” puts the unit only on its second endpoint.
        stated.update(float(value) for value in re.findall(r"(\d+(?:\.\d+)?)到\d+(?:\.\d+)?度", case["text"]))
        assert stated == expected, (case["id"], stated, expected)


